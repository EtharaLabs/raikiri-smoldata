def _extract():
    """Unpack the shipped snapshot; return the tree root inside it."""
    if not HARNESS_SRC.is_file():
        pytest.fail(f"{HARNESS_SRC} missing from the image")
    if hashlib.sha256(HARNESS_SRC.read_bytes()).hexdigest() != HARNESS_SRC_SHA:
        pytest.fail(f"{HARNESS_SRC} differs from the snapshot the image staged")
    dest = pathlib.Path(tempfile.mkdtemp())
    subprocess.run([_bin("tar"), "xzf", str(HARNESS_SRC), "-C", str(dest)],
                   check=True, timeout=EXTRACT_TIMEOUT)
    return dest / REPO_DIR


def _stage(tree):
    """Build `tree` with the harness script; a build failure raises rather than passes: a tree that
    will not compile must not read as one on which nothing crashes, which scores the same as a repair."""
    staged = tree.parent / "staged"
    subprocess.run([_bin("bash"), str(_harness_script("compile.sh")),
                    "patched", str(tree), str(staged)],
                   check=True, capture_output=True, text=True,
                   timeout=BUILD_TIMEOUT)
    return staged


def _verdict(staged, poc):
    """Ask the judge for a verdict, exactly as run_poc.sh does."""
    proc = subprocess.run(
        [sys.executable, str(JUDGE), "--target", str(staged),
         "--input", str(poc)],
        capture_output=True, text=True, timeout=JUDGE_TIMEOUT)
    return json.loads(proc.stdout)


def _variant_poc():
    """Materialise the second held-out variant input at grade time."""
    raw = base64.b64decode("".join(VARIANT_POC_B64.split()))
    assert hashlib.sha256(raw).hexdigest() == VARIANT_POC_SHA256, \
        "the embedded variant reproducer does not match its pinned digest"
    path = pathlib.Path(tempfile.mkdtemp()) / "variant_poc.bin"
    path.write_bytes(raw)
    return path


def _dict_index_poc():
    """Materialise a third held-out input at grade time. It faults in the dictionary-index
    decode path (RleDecoder::GetBatchWithDict[Spaced]), a different sub-case from the
    GetAligned bit-width fault the withheld and variant inputs exercise, so a repair that
    only bounds the bit width still fails it."""
    raw = base64.b64decode("".join(DICT_POC_B64.split()))
    assert hashlib.sha256(raw).hexdigest() == DICT_POC_SHA256, \
        "the embedded dictionary-index reproducer does not match its pinned digest"
    path = pathlib.Path(tempfile.mkdtemp()) / "dict_index_poc.bin"
    path.write_bytes(raw)
    return path


